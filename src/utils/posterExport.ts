/**
 * F1 Archive — High-DPI HTML5 Canvas Poster Exporter
 * Generates crisp 2x-3x resolution PNG telemetry cards for social sharing,
 * completely client-side with zero external bundle dependencies.
 */

export interface PosterRow {
  label: string;
  value: string;
  color?: string;
  subValue?: string;
}

export interface PosterExportOptions {
  title: string;
  subtitle: string;
  rows: PosterRow[];
  footerNote?: string;
  filename?: string;
}

export async function exportPosterAsPng(options: PosterExportOptions): Promise<void> {
  const {
    title,
    subtitle,
    rows,
    footerNote = 'Generated by F1 Archive • Strictly for educational & non-commercial research',
    filename = 'f1-archive-telemetry-poster.png'
  } = options;

  // Use 2x or 3x DPI for ultra-crisp typography
  const scale = 2.5;
  const baseWidth = 800;
  const rowHeight = 44;
  const headerHeight = 160;
  const footerHeight = 80;
  const baseHeight = headerHeight + rows.length * rowHeight + footerHeight;

  const canvas = document.createElement('canvas');
  canvas.width = baseWidth * scale;
  canvas.height = baseHeight * scale;

  const ctx = canvas.getContext('2d');
  if (!ctx) return;

  ctx.scale(scale, scale);

  // 1. Background Gradient
  const bgGrad = ctx.createLinearGradient(0, 0, baseWidth, baseHeight);
  bgGrad.addColorStop(0, '#05070C');
  bgGrad.addColorStop(1, '#0D1322');
  ctx.fillStyle = bgGrad;
  ctx.fillRect(0, 0, baseWidth, baseHeight);

  // 2. Subtle Cyber Grid Overlay
  ctx.strokeStyle = 'rgba(0, 210, 255, 0.05)';
  ctx.lineWidth = 1;
  const gridSize = 32;
  for (let x = 0; x < baseWidth; x += gridSize) {
    ctx.beginPath();
    ctx.moveTo(x, 0);
    ctx.lineTo(x, baseHeight);
    ctx.stroke();
  }
  for (let y = 0; y < baseHeight; y += gridSize) {
    ctx.beginPath();
    ctx.moveTo(0, y);
    ctx.lineTo(baseWidth, y);
    ctx.stroke();
  }

  // 3. Glowing Border Frame
  ctx.strokeStyle = 'rgba(0, 210, 255, 0.4)';
  ctx.lineWidth = 2;
  ctx.strokeRect(16, 16, baseWidth - 32, baseHeight - 32);

  // Corner Brackets
  ctx.strokeStyle = '#00D2FF';
  ctx.lineWidth = 3;
  const bSize = 16;
  // Top-left
  ctx.beginPath();
  ctx.moveTo(16, 16 + bSize);
  ctx.lineTo(16, 16);
  ctx.lineTo(16 + bSize, 16);
  ctx.stroke();
  // Top-right
  ctx.beginPath();
  ctx.moveTo(baseWidth - 16 - bSize, 16);
  ctx.lineTo(baseWidth - 16, 16);
  ctx.lineTo(baseWidth - 16, 16 + bSize);
  ctx.stroke();
  // Bottom-left
  ctx.beginPath();
  ctx.moveTo(16, baseHeight - 16 - bSize);
  ctx.lineTo(16, baseHeight - 16);
  ctx.lineTo(16 + bSize, baseHeight - 16);
  ctx.stroke();
  // Bottom-right
  ctx.beginPath();
  ctx.moveTo(baseWidth - 16 - bSize, baseHeight - 16);
  ctx.lineTo(baseWidth - 16, baseHeight - 16);
  ctx.lineTo(baseWidth - 16, baseHeight - 16 - bSize);
  ctx.stroke();

  // 4. Header Badge & Typography
  ctx.fillStyle = '#00D2FF';
  ctx.font = 'bold 12px "Share Tech Mono", monospace, sans-serif';
  ctx.fillText('F1 // ARCHIVE — RACE CONTROL TELEMETRY', 40, 48);

  ctx.fillStyle = '#FFFFFF';
  ctx.font = 'bold 24px "Titillium Web", sans-serif';
  ctx.fillText(title, 40, 84);

  ctx.fillStyle = '#8B93A7';
  ctx.font = '13px "Share Tech Mono", monospace, sans-serif';
  ctx.fillText(subtitle, 40, 112);

  // Dividing Line
  ctx.strokeStyle = 'rgba(0, 210, 255, 0.2)';
  ctx.lineWidth = 1;
  ctx.beginPath();
  ctx.moveTo(40, 130);
  ctx.lineTo(baseWidth - 40, 130);
  ctx.stroke();

  // 5. Data Rows
  let currentY = 160;
  rows.forEach((row, idx) => {
    // Alternating row background
    if (idx % 2 === 0) {
      ctx.fillStyle = 'rgba(255, 255, 255, 0.02)';
      ctx.fillRect(40, currentY - 20, baseWidth - 80, rowHeight - 6);
    }

    // Color dot / bar
    const accentColor = row.color || '#00D2FF';
    ctx.fillStyle = accentColor;
    ctx.fillRect(44, currentY - 14, 4, 18);

    // Label
    ctx.fillStyle = '#FFFFFF';
    ctx.font = 'bold 14px "Titillium Web", sans-serif';
    ctx.fillText(row.label, 56, currentY);

    // Value
    ctx.fillStyle = accentColor;
    ctx.font = 'bold 13px "Share Tech Mono", monospace, sans-serif';
    ctx.textAlign = 'right';
    ctx.fillText(row.value, baseWidth - 52, currentY);
    ctx.textAlign = 'left';

    currentY += rowHeight;
  });

  // 6. Footer Disclaimer & Timestamp
  ctx.strokeStyle = 'rgba(255, 255, 255, 0.1)';
  ctx.beginPath();
  ctx.moveTo(40, baseHeight - 50);
  ctx.lineTo(baseWidth - 40, baseHeight - 50);
  ctx.stroke();

  ctx.fillStyle = '#535E75';
  ctx.font = '10px "Share Tech Mono", monospace, sans-serif';
  ctx.fillText(footerNote, 40, baseHeight - 32);

  const dateStr = new Date().toISOString().slice(0, 10);
  ctx.textAlign = 'right';
  ctx.fillText(`ARCHIVE-ID: ${dateStr}-V1.1`, baseWidth - 40, baseHeight - 32);
  ctx.textAlign = 'left';

  // 7. Trigger Direct Download
  return new Promise((resolve) => {
    canvas.toBlob((blob) => {
      if (!blob) {
        resolve();
        return;
      }
      const url = URL.createObjectURL(blob);
      const link = document.createElement('a');
      link.href = url;
      link.download = filename;
      document.body.appendChild(link);
      link.click();
      document.body.removeChild(link);
      setTimeout(() => {
        URL.revokeObjectURL(url);
        resolve();
      }, 100);
    }, 'image/png');
  });
}
